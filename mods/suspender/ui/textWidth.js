const ADVANCE = new Map();
for (const [start, widths] of RUNS) {
    widths.forEach((width, i) => {
        ADVANCE.set(start + i, width);
    });
}
/** A wide character from a fallback font (CJK, emoji): about one em. */
const WIDE_EM = 1;
/** Any other character Geist does not have: more than Geist's average, so a guess errs towards "+N". */
const OTHER_EM = 0.62;
/**
 * Herdr's semibold Geist is a little wider: "Перевести авторизацию портала на"
 * at 13.5 px is drawn 246 px wide, the regular advances add up to 238.
 */
const SEMIBOLD = 1.034;
/** The width of `text` at `size` px of the mod, in the mod's px. */
export function textWidth(text, size, weight = "regular") {
    let em = 0;
    for (const ch of text) {
        const code = ch.codePointAt(0) ?? 0;
        em += (ADVANCE.get(code) ?? (code > 0x2e80 ? WIDE_EM * 1000 : OTHER_EM * 1000)) / 1000;
    }
    return modPx(em * size * (weight === "semibold" ? SEMIBOLD : 1));
}
export const uiMeasure = (text, size, weight) => textWidth(text, size, weight);
